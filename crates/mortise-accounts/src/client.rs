//! Native account client. The webview receives neither OIDC nor session tokens.
use crate::{Error, Result, protocol::*};
use mortise_crypto::identity::Device;
use openidconnect::{
    AuthorizationCode, ClientId, CsrfToken, Nonce, PkceCodeChallenge, RedirectUrl, Scope,
    TokenResponse,
    core::{CoreAuthenticationFlow, CoreClient},
};
use serde::{Serialize, de::DeserializeOwned};
use std::{
    io::{Read, Write},
    net::TcpListener,
    time::{Duration, Instant},
};
use zeroize::Zeroizing;

pub struct Client {
    base: String,
    token: Zeroizing<String>,
}
pub struct Request {
    method: String,
    path: String,
    body: Zeroizing<Vec<u8>>,
    proof: Proof,
}
impl Request {
    pub fn signed<T: Serialize>(
        device: &Device,
        method: &str,
        path: &str,
        token: &str,
        input: &T,
    ) -> Result<Self> {
        let body = if method == "GET" {
            Vec::new()
        } else {
            serde_json::to_vec(input).map_err(|_| Error::Unavailable)?
        };
        let proof = Proof::sign(device, method, path, token, &body)?;
        Ok(Self {
            method: method.into(),
            path: path.into(),
            body: Zeroizing::new(body),
            proof,
        })
    }
}
impl Client {
    pub fn new(base: &str, token: String) -> Result<Self> {
        let url = service_url(base)?;
        if url.path() != "/" {
            return Err(Error::Invalid("Account service must use a root URL."));
        }
        Ok(Self {
            base: base.trim_end_matches('/').into(),
            token: Zeroizing::new(token),
        })
    }
    pub fn token(&self) -> &str {
        &self.token
    }
    pub fn config(&self) -> Result<AuthConfig> {
        let agent = agent();
        let mut response = agent
            .get(format!("{}/v1/auth/config", self.base))
            .call()
            .map_err(|_| Error::Unavailable)?;
        if response.status().as_u16() != 200 {
            return Err(Error::Unavailable);
        }
        response
            .body_mut()
            .with_config()
            .limit(32 * 1024)
            .read_json()
            .map_err(|_| Error::Unavailable)
    }
    pub fn send<T: DeserializeOwned>(&self, request: Request) -> Result<T> {
        let proof = serde_json::to_string(&request.proof).map_err(|_| Error::Unavailable)?;
        let uri = format!("{}{}", self.base, request.path);
        let auth = format!("Bearer {}", self.token.as_str());
        let agent = agent();
        let mut response = match request.method.as_str() {
            "GET" => agent
                .get(&uri)
                .header("x-mortise-proof", &proof)
                .header("authorization", &auth)
                .call(),
            "POST" => agent
                .post(&uri)
                .header("x-mortise-proof", &proof)
                .header("authorization", &auth)
                .header("content-type", "application/json")
                .send(request.body.as_slice()),
            _ => return Err(Error::Invalid("Unsupported account operation.")),
        }
        .map_err(|_| Error::Unavailable)?;
        let status = response.status().as_u16();
        if status != 200 {
            return Err(match status {
                401 => Error::Unauthorized,
                403 => {
                    let body: serde_json::Value = response
                        .body_mut()
                        .with_config()
                        .limit(32 * 1024)
                        .read_json()
                        .unwrap_or_default();
                    if body["code"] == "untrusted_device" {
                        Error::Untrusted
                    } else {
                        Error::Forbidden
                    }
                }
                409 => Error::Conflict(
                    "This request changed or is no longer available. Refresh and try again.",
                ),
                400 => Error::Invalid("This request is invalid or has expired."),
                _ => Error::Unavailable,
            });
        }
        response
            .body_mut()
            .with_config()
            .limit(1024 * 1024)
            .read_json()
            .map_err(|_| Error::Unavailable)
    }
}
fn agent() -> ureq::Agent {
    ureq::Agent::config_builder()
        .http_status_as_error(false)
        .max_redirects(0)
        .timeout_global(Some(Duration::from_secs(15)))
        .build()
        .into()
}

/// Sign in through the system browser. Caller opens ONLY the URL generated by
/// this flow. No account provider password or token is passed to the webview.
pub fn browser_login(
    config: &AuthConfig,
    nonce: &str,
    open: impl FnOnce(&str) -> Result<()>,
) -> Result<Zeroizing<String>> {
    let metadata = crate::oidc::discover(config)?;
    let listener =
        TcpListener::bind(("127.0.0.1", config.callback_port.unwrap_or(0))).map_err(|_| {
            Error::Invalid(
                "The sign-in callback port is busy. Close the other sign-in attempt and retry.",
            )
        })?;
    listener
        .set_nonblocking(true)
        .map_err(|_| Error::Unavailable)?;
    let redirect = format!(
        "http://127.0.0.1:{}/callback",
        listener
            .local_addr()
            .map_err(|_| Error::Unavailable)?
            .port()
    );
    let client =
        CoreClient::from_provider_metadata(metadata, ClientId::new(config.client_id.clone()), None)
            .set_redirect_uri(RedirectUrl::new(redirect.clone()).map_err(|_| Error::Unavailable)?);
    let (challenge, verifier) = PkceCodeChallenge::new_random_sha256();
    let login_nonce = nonce.to_string();
    let mut authorization = client
        .authorize_url(
            CoreAuthenticationFlow::AuthorizationCode,
            CsrfToken::new_random,
            move || Nonce::new(login_nonce),
        )
        .add_scope(Scope::new("email".into()))
        .add_scope(Scope::new("profile".into()))
        .set_pkce_challenge(challenge);
    if let Some(resource) = &config.resource {
        service_url(resource)?;
        authorization = authorization.add_extra_param("resource", resource);
    }
    let (url, state, _) = authorization.url();
    open(url.as_str())?;
    let deadline = Instant::now() + Duration::from_secs(180);
    let code = loop {
        if Instant::now() > deadline {
            return Err(Error::Invalid("Sign-in timed out. Try again."));
        }
        match listener.accept() {
            Ok((mut stream, _)) => {
                let _ = stream.set_read_timeout(Some(Duration::from_secs(2)));
                let _ = stream.set_write_timeout(Some(Duration::from_secs(2)));
                let mut bytes = Vec::new();
                let mut chunk = [0u8; 1024];
                while bytes.len() < 8192 && !bytes.windows(4).any(|w| w == b"\r\n\r\n") {
                    match stream.read(&mut chunk) {
                        Ok(0) | Err(_) => break,
                        Ok(n) => bytes.extend_from_slice(&chunk[..n]),
                    }
                }
                let request = String::from_utf8_lossy(&bytes);
                let result = callback_code(&request, state.secret());
                let (status, message) = if result.is_ok() {
                    ("200 OK", "You can return to Mortise.")
                } else {
                    (
                        "400 Bad Request",
                        "Invalid sign-in response. Return to Mortise and try again.",
                    )
                };
                let response = format!(
                    "HTTP/1.1 {status}\r\nContent-Type: text/plain\r\nCache-Control: no-store\r\nConnection: close\r\nContent-Length: {}\r\n\r\n{message}",
                    message.len()
                );
                let _ = stream.write_all(response.as_bytes());
                if let Ok(code) = result {
                    break code;
                }
            }
            Err(e) if e.kind() == std::io::ErrorKind::WouldBlock => {
                std::thread::sleep(Duration::from_millis(50))
            }
            Err(_) => return Err(Error::Unavailable),
        }
    };
    let mut exchange = client
        .exchange_code(AuthorizationCode::new(code))
        .map_err(|_| Error::Unavailable)?
        .set_pkce_verifier(verifier);
    if let Some(resource) = &config.resource {
        exchange = exchange.add_extra_param("resource", resource);
    }
    let response = exchange
        .request(&crate::oidc::http)
        .map_err(|_| Error::Unauthorized)?;
    let token = response.id_token().ok_or(Error::Unauthorized)?;
    // Validate locally as well; the server independently checks its login nonce.
    token
        .claims(&client.id_token_verifier(), &Nonce::new(nonce.into()))
        .map_err(|_| Error::Unauthorized)?;
    Ok(Zeroizing::new(token.to_string()))
}

pub fn callback_code(request: &str, expected_state: &str) -> Result<String> {
    let first = request.lines().next().ok_or(Error::Unauthorized)?;
    let parts: Vec<_> = first.split_whitespace().collect();
    if parts.len() != 3
        || parts[0] != "GET"
        || parts[2] != "HTTP/1.1"
        || !parts[1].starts_with("/callback?")
    {
        return Err(Error::Unauthorized);
    }
    let url = url::Url::parse(&format!("http://127.0.0.1{}", parts[1]))
        .map_err(|_| Error::Unauthorized)?;
    let params: Vec<_> = url.query_pairs().collect();
    let state: Vec<_> = params.iter().filter(|(k, _)| k == "state").collect();
    let code: Vec<_> = params.iter().filter(|(k, _)| k == "code").collect();
    if state.len() != 1
        || code.len() != 1
        || params.iter().any(|(k, _)| k == "error")
        || digest(&state[0].1) != digest(expected_state)
        || code[0].1.is_empty()
        || code[0].1.len() > 4096
    {
        return Err(Error::Unauthorized);
    }
    Ok(code[0].1.to_string())
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn callbacks_reject_wrong_state_duplicate_parameters_and_wrong_routes() {
        assert_eq!(
            callback_code(
                "GET /callback?state=expected&code=good HTTP/1.1\r\n\r\n",
                "expected"
            )
            .unwrap(),
            "good"
        );
        for request in [
            "GET /callback?state=wrong&code=good HTTP/1.1",
            "GET /callback?state=expected&state=other&code=good HTTP/1.1",
            "GET /callback?state=expected&code=one&code=two HTTP/1.1",
            "GET /other?state=expected&code=good HTTP/1.1",
            "POST /callback?state=expected&code=good HTTP/1.1",
            "GET /callback?state=expected&code=good&error=denied HTTP/1.1",
        ] {
            assert!(callback_code(request, "expected").is_err());
        }
    }
}
